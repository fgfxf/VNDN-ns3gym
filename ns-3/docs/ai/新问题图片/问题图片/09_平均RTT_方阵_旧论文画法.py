def draw():
    plt.rcParams.update({'font.family': 'serif', 'font.serif': [FONT_FAMILY],
                         'font.size': FONT_SIZE, 'axes.labelsize': FONT_SIZE,
                         'axes.linewidth': .7, 'xtick.direction': 'in',
                         'ytick.direction': 'in', 'pdf.fonttype': 42, 'ps.fonttype': 42,
                         'svg.fonttype': 'path', 'savefig.facecolor': 'white'})
    fig = plt.figure(figsize=FIGSIZE)
    ax = fig.add_subplot(111, projection='3d')
    for series in DATA:
        strategy = series['strategy']
        ax.plot(series['x'], [strategy] * len(series['rtt_ms']), series['rtt_ms'],
                color=COLORS[strategy], linestyle=LINES[strategy],
                marker=MARKERS[strategy], markersize=MARKER_SIZE, linewidth=LINE_WIDTH)
    ax.set_xlabel('Interest generation time (s)', labelpad=8)
    ax.set_xticks((20, 50, 80, 110, 140))
    ax.set_xlim(20, 140)
    ax.set_ylim(-.2, 3.2)
    ax.set_yticks(range(4))
    ax.set_yticklabels(ALGORITHMS, fontsize=8)
    values = [v for series in DATA for v in series['rtt_ms']]
    low, high = min(values), max(values)
    high += max(high-low, 1.) * .10
    ticks = [low] + [float(t) for t in MaxNLocator(nbins=5).tick_values(low,high)
                     if low+(high-low)*.08 < t <= high]
    ax.set_zticks(ticks)
    ax.set_zlim(low, high)
    ax.zaxis.set_major_formatter(FuncFormatter(lambda value, _: '{:.1f}'.format(value).rstrip('0').rstrip('.')))
    ax.tick_params(axis='z', labelsize=8)
    ax.text2D(1.18, .52, RTT_LABEL, transform=ax.transAxes,
              rotation=90, ha='center', va='center', fontsize=9)
    ax.view_init(elev=27, azim=-58)
    ax.set_box_aspect((1.25, 1., .9))
    ax.text2D(.5, -.10, SCENE_LABEL, transform=ax.transAxes, ha='center', fontsize=12)
    handles = [Line2D([], [], color=COLORS[i], linestyle=LINES[i], marker=MARKERS[i],
                      markersize=MARKER_SIZE, linewidth=LINE_WIDTH, label=ALGORITHMS[i]) for i in range(4)]
    fig.legend(handles=handles, loc='upper center', ncol=4, bbox_to_anchor=(.5,.99),
               frameon=True, fancybox=False, edgecolor='black', framealpha=1)
    fig.subplots_adjust(left=.03, right=.87, bottom=.13, top=.85)
    return fig


