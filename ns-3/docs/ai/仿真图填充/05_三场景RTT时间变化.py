X_LIM = (20, 140)
Y_LIM = (-0.2, 3.2)
Z_LIM = None  # None按全部数据自动设置共同范围；也可设(0, 650)
X_TICKS = (20, 50, 80, 110, 140)
Z_TICKS = None
VIEW_ELEVATION = 27
VIEW_AZIMUTH = -58
LINE_WIDTH = 1.0
MARKER_SIZE = 3


def setup_style():
    plt.rcParams.update({
        'font.family': 'serif', 'font.serif': [FONT_FAMILY],
        'font.size': FONT_SIZE, 'axes.labelsize': FONT_SIZE - 1,
        'xtick.labelsize': FONT_SIZE - 2, 'ytick.labelsize': FONT_SIZE - 2,
        'legend.fontsize': FONT_SIZE, 'legend.frameon': True,
        'legend.fancybox': False, 'legend.edgecolor': 'black',
        'legend.framealpha': 1, 'pdf.fonttype': 42,
        'ps.fonttype': 42, 'svg.fonttype': 'path', 'savefig.facecolor': 'white',
    })


def draw():
    fig = plt.figure(figsize=FIGSIZE)
    values = [value for scene in SCENES for series in DATA[scene]
              for value in series['rtt_ms'] if value is not None]
    zlim = Z_LIM if Z_LIM is not None else (0, max(50, np.ceil(max(values, default=0) * 1.08 / 50) * 50))
    for panel, scene in enumerate(SCENES):
        ax = fig.add_subplot(1, 3, panel + 1, projection='3d')
        for series in DATA[scene]:
            strategy = series['strategy']
            # 空时间桶必须断线，不把缺失的成功RTT画成零。
            z = [np.nan if value is None else value for value in series['rtt_ms']]
            ax.plot(series['x'], [strategy] * len(z), z,
                    color=COLORS[strategy], linestyle=LINES[strategy],
                    marker=MARKERS[strategy], markersize=MARKER_SIZE,
                    linewidth=LINE_WIDTH)
        ax.set(xlabel='Interest generation time (s)',
               xlim=X_LIM, ylim=Y_LIM, zlim=zlim)
        ax.set_yticks(range(4), ALGORITHMS, fontsize=8)
        # 三维z轴默认标签未被Matplotlib完整计入tight边界，改用明确的二维标签。
        ax.text2D(1.08, 0.52, 'Mean successful RTT (ms)', transform=ax.transAxes,
                  rotation=90, ha='center', va='center', fontsize=9)
        ax.tick_params(axis='z', labelsize=8)
        if X_TICKS is not None:
            ax.set_xticks(X_TICKS)
        if Z_TICKS is not None:
            ax.set_zticks(Z_TICKS)
        ax.view_init(elev=VIEW_ELEVATION, azim=VIEW_AZIMUTH)
        ax.set_box_aspect((1.25, 1, 0.9))
        ax.text2D(0.5, -0.14, '({}) {}'.format('abc'[panel], SCENE_LABELS[panel]),
                  transform=ax.transAxes, ha='center', fontsize=FONT_SIZE + 1)
    handles = [Line2D([], [], color=COLORS[i], linestyle=LINES[i], marker=MARKERS[i],
                      label=ALGORITHMS[i]) for i in range(4)]
    fig.legend(handles=handles, loc='upper center', ncol=4, bbox_to_anchor=(0.5, 0.99))
    fig.subplots_adjust(left=0.015, right=0.97, bottom=0.16, top=0.89, wspace=0.13)
    return fig


def save(fig):
    folder = Path(__file__).resolve().parent
    pending = []
    try:
        for extension in ('png', 'svg', 'pdf'):
            target = folder / (FIGURE_ID + '.' + extension)
            temporary = folder / ('.' + FIGURE_ID + '.pending.' + extension)
            pending.append((temporary, target))
            fig.savefig(temporary, format=extension, dpi=DPI, bbox_inches='tight')
        for temporary, target in pending:
            temporary.replace(target)
    finally:
        plt.close(fig)
        for temporary, _ in pending:
            if temporary.exists():
                temporary.unlink()
    print('已更新：' + FIGURE_ID + '（PNG / SVG / PDF）')


def main():
    setup_style()
    save(draw())


