def validate_data():
    if set(DATA) != set(SCENES):
        raise ValueError('DATA must contain all three scenes')
    for scene in SCENES:
        if [series['strategy'] for series in DATA[scene]] != list(range(4)):
            raise ValueError('Keep all four strategies in their original order')
        for series in DATA[scene]:
            x, y = series['x'], series['rtt_ms']
            if not x or len(x) != len(y) or not np.isfinite(x).all():
                raise ValueError('Coordinates must have matching nonempty lengths and finite times')
            if not all(a < b for a, b in zip(x, x[1:])):
                raise ValueError('Generation-time bin centers must be increasing')
            if any(value is not None and (not np.isfinite(value) or value < 0) for value in y):
                raise ValueError('RTT must be nonnegative and finite, or None for a missing bin')


def limits(scene, three_dimensional):
    values = [v for series in DATA[scene] for v in series['rtt_ms'] if v is not None]
    if not values:
        raise ValueError('Cannot determine an axis range from an entirely empty scene')
    minimum, maximum = min(values), max(values)
    span = max(maximum - minimum, 1.)
    custom = Z_LIMS if three_dimensional else Y_LIMS
    bounds = custom[scene] if custom is not None else (
        minimum if three_dimensional else max(0., minimum - .07 * span), maximum + .10 * span)
    if len(bounds) != 2 or not np.isfinite(bounds).all() or bounds[0] >= bounds[1]:
        raise ValueError('Axis limits must be finite and increasing')
    if bounds[0] > minimum or bounds[1] < maximum:
        raise ValueError('Axis limits must include all existing RTT values')
    return bounds


def draw():
    validate_data()
    setup_style()
    is_3d = PLOT_KIND == '3d'
    fig = plt.figure(figsize=FIGSIZE)
    for panel, scene in enumerate(SCENES):
        ax = fig.add_subplot(1, 3, panel + 1, projection='3d' if is_3d else None)
        for series in DATA[scene]:
            strategy = series['strategy']
            y = [np.nan if value is None else value for value in series['rtt_ms']]
            arguments = (series['x'], [strategy] * len(y), y) if is_3d else (series['x'], y)
            ax.plot(*arguments, color=COLORS[strategy], linestyle=LINES[strategy],
                    marker=MARKERS[strategy], markersize=MARKER_SIZE, linewidth=LINE_WIDTH)
        ax.set_xlabel('Interest generation time (s)', labelpad=8)
        ax.set_xticks(X_TICKS)
        ax.set_xlim(*X_LIM)
        low, high = limits(scene, is_3d)
        if is_3d:
            ax.set_ylim(-.2, 3.2)
            ax.set_yticks(range(4), ALGORITHMS, fontsize=8)
            ticks = [low] + [float(t) for t in MaxNLocator(nbins=5).tick_values(low, high)
                             if low + (high - low) * .08 < t <= high]
            ax.set_zticks(ticks)
            ax.set_zlim(low, high)
            ax.zaxis.set_major_formatter(FuncFormatter(lambda value, _: '{:.1f}'.format(value).rstrip('0').rstrip('.')))
            ax.tick_params(axis='z', labelsize=8)
            # 明确纳入tight导出范围，避免三维z标签被裁切。
            ax.text2D(1.08, .52, RTT_LABEL, transform=ax.transAxes,
                      rotation=90, ha='center', va='center', fontsize=9)
            ax.view_init(elev=VIEW_ELEVATION, azim=VIEW_AZIMUTH)
            ax.set_box_aspect((1.25, 1., .9))
            ax.text2D(.5, -.14, '({}) {}'.format('abc'[panel], SCENE_LABELS[panel]),
                      transform=ax.transAxes, ha='center', fontsize=FONT_SIZE + 1)
        else:
            ax.set_ylabel(RTT_LABEL, labelpad=8)
            ax.set_ylim(low, high)
            ax.ticklabel_format(axis='y', style='plain', useOffset=False)
            ax.grid(axis='y', alpha=.22)
            ax.tick_params(top=True, right=True)
            ax.text(.5, -.25, '({}) {}'.format('abc'[panel], SCENE_LABELS[panel]),
                    transform=ax.transAxes, ha='center', fontsize=FONT_SIZE + 1)
    handles = [Line2D([], [], color=COLORS[i], linestyle=LINES[i], marker=MARKERS[i],
                      markersize=MARKER_SIZE, linewidth=LINE_WIDTH, label=ALGORITHMS[i]) for i in range(4)]
    fig.legend(handles=handles, loc='upper center', ncol=4, bbox_to_anchor=(.5, .99))
    if is_3d:
        fig.subplots_adjust(left=.015, right=.97, bottom=.16, top=.89, wspace=.13)
    else:
        fig.subplots_adjust(left=.06, right=.985, bottom=.24, top=.85, wspace=.30)
    return fig


def save(fig):
    folder = Path(__file__).resolve().parent
    pending = []
    try:
        for extension in ('png', 'svg', 'pdf'):
            target = folder / (FIGURE_ID + '.' + extension)
            temporary = folder / ('.' + FIGURE_ID + '.pending.' + extension)
            pending.append((temporary, target))
            fig.savefig(temporary, format=extension, dpi=DPI, bbox_inches='tight', pad_inches=.12)
        for temporary, target in pending:
            temporary.replace(target)
    finally:
        plt.close(fig)
        for temporary, _ in pending:
            if temporary.exists():
                temporary.unlink()
    print('已更新：' + FIGURE_ID + '（PNG / SVG / PDF）')


def main():
    save(draw())


